# Program: Data Types in Python
# Description: Demonstrates the basic data types in Python.

# String
language = "Python"

# Integer
number = 100

# Float
price = 99.99

# Boolean
is_available = True

# List
fruits = ["Apple", "Banana", "Mango"]

# Tuple
colors = ("Red", "Green", "Blue")

# Dictionary
student = {
    "Name": "John",
    "Age": 20,
    "Course": "Python"
}

# Set
unique_numbers = {10, 20, 30, 40}

print("String:", language)
print("Integer:", number)
print("Float:", price)
print("Boolean:", is_available)
print("List:", fruits)
print("Tuple:", colors)
print("Dictionary:", student)
print("Set:", unique_numbers)
